// Add new book vocabulary to existing installations without resetting learning progress.
// This runs before app.js loads. Custom cards, settings and progress remain untouched.
(() => {
  'use strict';
  const storageKey = 'vokabeltrainer-state-v1';
  try {
    const raw = localStorage.getItem(storageKey);
    if (!raw) return; // app.js will seed all cards on first launch
    const state = JSON.parse(raw);
    if (!state || !Array.isArray(state.cards)) return;
    const normalize = value => String(value || '').trim().toLocaleLowerCase('de');
    const makeKey = c => [c.chapter, c.section, c.english].map(normalize).join('|');
    const knownIds = new Set(state.cards.map(c => c.id).filter(Boolean));
    const knownKeys = new Set(state.cards.map(makeKey));
    let added = 0;
    for (const card of window.SEED_VOCAB.slice(150)) { // only newly added Units 2–4
      const key = makeKey(card);
      if (knownIds.has(card.id) || knownKeys.has(key)) continue;
      state.cards.push({...card});
      knownIds.add(card.id);
      knownKeys.add(key);
      added++;
    }
    if (added) localStorage.setItem(storageKey, JSON.stringify(state));
  } catch (error) {
    // The main app can still load its previous local data if migration fails.
    console.warn('Vocabulary update could not be applied:', error);
  }
})();
